"""诸葛亮半年步数据（按人生阶段分块编写）。confidence: documented / inferred / traditional。"""


def step(sid: str, places: list[str], event: str, conf: str, sources: list[str], stage: str,
         milestone: dict | None = None, note: str | None = None) -> dict:
    d = {'id': sid, 'places': places, 'event': event, 'confidence': conf, 'sources': sources, 'stage': stage}
    if milestone:
        d['milestone'] = milestone
    if note:
        d['note'] = note
    return d


def ms(title: str, subtitle: str, importance: int, quote: str | None = None, qsrc: str | None = None) -> dict:
    m = {'title': title, 'subtitle': subtitle, 'importance': importance}
    if quote:
        m['quote'] = {'text': quote, 'source': qsrc}
    return m


def span(y0: int, h0: int, y1: int, h1: int) -> list[str]:
    """闭区间内的全部半年 id。"""
    out, y, h = [], y0, h0
    while (y, h) <= (y1, h1):
        out.append(f'{y}H{h}')
        y, h = (y, 2) if h == 1 else (y + 1, 1)
    return out


