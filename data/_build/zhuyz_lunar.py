def convert(year: int, month: int, day) -> str:
    """day 为整数（日序）或干支字符串；干支不在该月内时报错，避免静默错配。"""
    if isinstance(day, int):
        return Lunar.fromYmd(year, month, day).getSolar().toYmd()
    for d in range(1, 31):
        try:
            lu = Lunar.fromYmd(year, month, d)
        except Exception:  # 小月没有三十日
            break
        if lu.getDayInGanZhi() == day:
            return f'{lu.getSolar().toYmd()} (初{d}日起算第{d}日)'
    raise ValueError(f'{year}年{month}月 无 {day} 日')


