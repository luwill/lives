def st(sid: str, places: list[str], event: str, conf: str, sources: list[str], stage: str,
       milestone: dict | None = None, note: str | None = None) -> dict:
    """组装一条半年步；字段顺序与 SCHEMA 一致。"""
    rec = {'id': sid, 'places': places, 'event': event, 'confidence': conf, 'sources': sources, 'stage': stage}
    if milestone:
        rec['milestone'] = milestone
    if note:
        rec['note'] = note
    return rec


def ms(title: str, subtitle: str, importance: int, place: str | None = None,
       quote: tuple[str, str] | None = None) -> dict:
    m = {'title': title, 'subtitle': subtitle, 'importance': importance}
    if place:
        m['place'] = place
    if quote:
        m['quote'] = {'text': quote[0], 'source': quote[1]}
    return m


